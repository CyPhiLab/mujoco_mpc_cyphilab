#!/usr/bin/env python3
"""Exports optimized gaits to MJPC and as standalone packages.

  export_gaits.py --run runs/A [--names v0.04 v0.08 max]
      [--mjpc ../gait_reference.xml] [--package export_A] [--hz 100]

--run picks, for every gait name in the run's summary.json, the step at the
finest timestep (the last one written for that name). Gaits can also be
given one by one as NAME=STEP.npz.

Writes
  --mjpc      gait_reference.xml for task.xml: residual_list_Gait
              ("Off|<names>") and one numeric gait_<name> per gait
              (period, K, steady speed, swim direction, then the command's
              Fourier coefficients in
              radians; see PaddleCrabGait in paddle_crab_swimming.cc)
  --package   a standalone directory: model.xml (the patched robot with the
              servo filter as built-in dynamics, no MJPC needed), assets,
              gaits.npz (coefficients, one-cycle command tables at --hz,
              joint-angle limit cycles), replay.py and a README; the replay
              is checked against the optimizer's own rollout
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys

import mujoco
import numpy as np

import crab_model as C
import gait_opt as G


def load_step(path):
  z = np.load(path, allow_pickle=True)
  return dict(path=path, theta=z['theta'], k=int(z['k']), dt=float(z['dt']),
              metrics=json.loads(str(z['metrics'])), phase=z['phase'],
              qpos=z['qpos'], ctrl=z['ctrl'], warm=int(z['warm']),
              measure=int(z['measure']),
              half=z['half'] if 'half' in z else None,
              direction=(z['direction'] if 'direction' in z
                         else C.FORWARD).astype(float))


def pick_from_run(run, names=None):
  with open(os.path.join(run, 'summary.json')) as f:
    summary = json.load(f)
  best = {}
  for row in summary:
    name = re.sub(r'_dt[0-9.e-]+.*$', '', row['name'])
    if row.get('stage') == 'search':
      continue
    # Later rows of a name are finer timesteps (or the ES retry).
    best[name] = row
  if names:
    best = {n: best[n] for n in names}
  return {n: os.path.join(run, r['file']) for n, r in best.items()}


STEADY_WARM = 12   # cycles from rest before the steady-state window


def steady_metrics(step):
  """Metrics on the true limit cycle: STEADY_WARM cycles from rest, then 2.

  The optimizer scores cycles warm+1..warm+measure (4-5 by default), while
  the body is still speeding up; this is where it ends up.
  """
  problem = G.Problem(dt=C.SIM_DT, k=step['k'], warm=STEADY_WARM, measure=2,
                      direction=step['direction'],
                      ctrl_limit=ctrl_limit(step['half']))
  _, info = problem.evaluate(step['theta'][None])
  return info[0]


def ctrl_limit(half):
  """The uniform command limit a gait was optimized with, or None for the
  task's own ctrlranges."""
  if half is None or not np.allclose(half, half[0]):
    return None
  return float(half[0])


def coefficients(theta, k, half):
  """(period, c, a, b) in radians from a normalized theta."""
  layout = G.Layout(k)
  log_t, c, a, b = layout.split(theta)
  return (float(np.exp(log_t)), c * half, a * half[:, None],
          b * half[:, None])


def check_unclipped(theta, k, n=400):
  """The MJPC callback clamps c + series per actuator, like the optimizer's
  clip; the two agree exactly. Report how much of the cycle is clipped."""
  layout = G.Layout(k)
  raw = G.raw_command(layout, theta, np.arange(n) / n)
  return float(np.mean(np.abs(raw) > 1))


def write_mjpc(path, gaits, half):
  lines = ['<!-- Generated by analysis/export_gaits.py; do not edit by hand.',
           '     Each gait_<name> holds: period (s), K, speed (m/s), swim',
           '     direction (3, world; the body keeps its heading), then the',
           '     servo command per actuator as a Fourier series in phase, in',
           '     radians: c (18), a (18 x K), b (18 x K). -->',
           '<mujoco>', '  <custom>',
           '    <text name="residual_list_Gait" data="Off|%s" />'
           % '|'.join(gaits)]
  for name, step in gaits.items():
    period, c, a, b = coefficients(step['theta'], step['k'], step['half'])
    data = np.concatenate([[period, step['k'], step['steady']['speed']],
                           step['direction'], c, a.ravel(), b.ravel()])
    text = ' '.join(f'{x:.9g}' for x in data)
    lines.append(f'    <numeric name="gait_{name}" data="{text}" />')
  lines += ['  </custom>', '</mujoco>', '']
  with open(path, 'w') as f:
    f.write('\n'.join(lines))
  print('wrote', path)


REPLAY = '''#!/usr/bin/env python3
"""Replays an exported gait open loop from rest: python replay.py [NAME] [CYCLES]

Needs only the mujoco and numpy packages. The servos in model.xml carry the
setpoint filter (tau = {tau} s) as MuJoCo "filter" dynamics, so ctrl is the
raw periodic command from gaits.npz.
"""
import os
import sys

import mujoco
import numpy as np

here = os.path.dirname(os.path.abspath(__file__))
m = mujoco.MjModel.from_xml_path(os.path.join(here, 'model.xml'))
d = mujoco.MjData(m)
g = np.load(os.path.join(here, 'gaits.npz'))
names = list(g['names'])
name = sys.argv[1] if len(sys.argv) > 1 else names[0]
cycles = float(sys.argv[2]) if len(sys.argv) > 2 else 6
i = names.index(name)
period, k = float(g['period'][i]), int(g['k'][i])
c, a, b = g['c'][i], g['a'][i][:, :k], g['b'][i][:, :k]
lo, hi = m.actuator_ctrlrange.T
ks = np.arange(1, k + 1)


def command(t):
  w = 2 * np.pi * ks * t / period
  return np.clip(c + a @ np.cos(w) + b @ np.sin(w), lo, hi)


direction = g['direction'][i]
p0 = d.qpos[:3].copy()
while d.time < cycles * period:
  d.ctrl[:] = command(d.time)
  mujoco.mj_step(m, d)
print(f'{{name}}: {{cycles:g}} cycles of T = {{period:.3f}} s, '
      f'mean speed {{(d.qpos[:3] - p0) @ direction / d.time:.4f}} m/s '
      f'along {{direction}} (from rest)')
'''


def write_package(out, gaits, half, hz):
  os.makedirs(out, exist_ok=True)
  xml = C.patched_xml()
  xml = xml.replace('<include file="hfield_ground.xml" />',
                    '<compiler meshdir="assets" />')
  xml = xml.replace('dyntype="user"',
                    f'dyntype="filter" dynprm="{C.TAU:g}"')
  with open(os.path.join(out, 'model.xml'), 'w') as f:
    f.write(xml)
  os.makedirs(os.path.join(out, 'assets'), exist_ok=True)
  shutil.copy(os.path.join(C.TASK_DIR, 'asset', 'Swimming_Paddle.stl'),
              os.path.join(out, 'assets'))

  kmax = max(s['k'] for s in gaits.values())
  table = dict(names=np.array(list(gaits)), period=[], k=[], speed=[],
               direction=[],
               c=[], a=[], b=[], table_time=[], table_ctrl=[],
               joint_phase=[], joint_qpos=[])
  for name, step in gaits.items():
    period, c, a, b = coefficients(step['theta'], step['k'], step['half'])
    pad = lambda x: np.pad(x, ((0, 0), (0, kmax - x.shape[1])))
    n = int(round(period * hz))
    t = np.arange(n) / hz
    layout = G.Layout(step['k'])
    raw = G.raw_command(layout, step['theta'], t / period)
    table['period'].append(period)
    table['k'].append(step['k'])
    table['speed'].append(step['steady']['speed'])
    table['direction'].append(step['direction'])
    table['c'].append(c)
    table['a'].append(pad(a))
    table['b'].append(pad(b))
    table['table_time'].append(t)
    table['table_ctrl'].append((np.clip(raw, -1, 1) * step['half'][:, None]).T)
    table['joint_phase'].append(step['phase'])
    table['joint_qpos'].append(step['qpos'][:, 7:])
    np.savetxt(os.path.join(out, f'{name}_commands_{hz:g}hz.csv'),
               np.column_stack([t, table['table_ctrl'][-1]]), delimiter=',',
               header='time,' + ','.join(C.ACTUATORS), comments='', fmt='%.6f')
  arrays = {}
  for key, value in table.items():
    try:
      arrays[key] = np.array(value)
    except ValueError:      # ragged per-gait tables
      arrays[key] = np.array(value, dtype=object)
  np.savez(os.path.join(out, 'gaits.npz'), actuators=np.array(C.ACTUATORS),
           joints=np.array(C.JOINTS), **arrays)
  with open(os.path.join(out, 'replay.py'), 'w') as f:
    f.write(REPLAY.format(tau=C.TAU))

  # Replay check: the package against the optimizer's own model.
  rows = []
  for name, step in gaits.items():
    cycles = step['warm'] + step['measure']
    out_text = subprocess.run(
        [sys.executable, os.path.join(out, 'replay.py'), name, str(cycles)],
        check=True, capture_output=True, text=True).stdout.strip()
    replay_speed = float(re.search(r'speed ([-0-9.]+)', out_text).group(1))
    problem = G.Problem(dt=C.SIM_DT, k=step['k'], warm=cycles, measure=1,
                        direction=step['direction'],
                        ctrl_limit=ctrl_limit(step['half']))
    states, _, _ = problem.rollout(step['theta'][None])
    L = problem.state_layout
    n = int(np.ceil(cycles * np.exp(step['theta'][0]) / C.SIM_DT))
    ref_speed = (states[0, n, L.qpos][:3] - states[0, 0, L.qpos][:3]) @ (
        step['direction']) / (n * C.SIM_DT)
    rows.append((name, step['steady']['speed'], replay_speed, ref_speed))
    print(f'  {out_text}  [optimizer model from rest: {ref_speed:.4f}]')

  readme = [f'# Paddle crab gait primitives ({os.path.basename(out)})', '',
            'Made by `mjpc/tasks/paddle_crab_swimming/analysis/gait_chain.py`'
            ' and exported by `export_gaits.py`.', '',
            '- `model.xml`: the MJPC robot (after `patch_paddle_crab_robot.py`)'
            ' with the servo setpoint filter as built-in `filter` dynamics '
            f'(tau = {C.TAU:g} s), 1 ms timestep, contacts off, zero gravity.',
            '- `gaits.npz`: per gait the period, Fourier coefficients of the '
            'servo command (radians), one-cycle command tables at '
            f'{hz:g} Hz and the joint-angle limit cycle.',
            f'- `<name>_commands_{hz:g}hz.csv`: one cycle of servo commands '
            '(radians), actuator order R1_1 ... L3_3; loop it. On hardware '
            f'the commands assume a first-order setpoint lag of {C.TAU:g} s.',
            '- `replay.py [NAME] [CYCLES]`: open-loop replay from rest.', '',
            '| gait | direction | period (s) | steady speed (m/s) | '
            'replay from rest (m/s) |', '|---|---|---|---|---|']
  for (name, speed, replay, _), period, direction in zip(
      rows, table['period'], table['direction']):
    readme.append(f'| {name} | {np.round(direction, 2).tolist()} | '
                  f'{period:.3f} | {speed:.4f} | {replay:.4f} |')
  readme.append('')
  readme.append('The replay average includes the start-up transient from '
                'rest, so it is lower than the limit-cycle speed.')
  with open(os.path.join(out, 'README.md'), 'w') as f:
    f.write('\n'.join(readme) + '\n')
  print('wrote', out)


def main():
  p = argparse.ArgumentParser()
  p.add_argument('gaits', nargs='*', help='NAME=STEP.npz')
  p.add_argument('--run')
  p.add_argument('--names', nargs='*')
  p.add_argument('--mjpc')
  p.add_argument('--package')
  p.add_argument('--hz', type=float, default=100)
  args = p.parse_args()

  paths = pick_from_run(args.run, args.names) if args.run else {}
  for item in args.gaits:
    name, path = item.split('=')
    paths[name] = path
  gaits = {n: load_step(path) for n, path in paths.items()}
  half = C.load_model(ground=False).actuator_ctrlrange[:, 1].copy()
  for step in gaits.values():
    if step['half'] is None:
      step['half'] = half
  for name, step in gaits.items():
    step['steady'] = steady_metrics(step)
    print(f'{name}: {step["path"]} dt {step["dt"]} '
          f'v {step["metrics"]["speed"]:.4f} (steady '
          f'{step["steady"]["speed"]:.4f}) T {step["metrics"]["period"]:.3f}'
          f' clipped {check_unclipped(step["theta"], step["k"]):.3f}')
  if args.run:
    with open(os.path.join(args.run, 'steady.json'), 'w') as f:
      json.dump({n: s['steady'] for n, s in gaits.items()}, f, indent=2)
  if args.mjpc:
    write_mjpc(args.mjpc, gaits, half)
  if args.package:
    write_package(args.package, gaits, half, args.hz)


if __name__ == '__main__':
  main()
