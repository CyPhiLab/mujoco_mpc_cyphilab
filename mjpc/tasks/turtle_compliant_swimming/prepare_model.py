#!/usr/bin/env python3
"""Vendor turtle_simulator's compliant-flipper turtle into this task.

  python prepare_model.py --turtle-sim ../../../../turtle_simulator

Reads mujoco_models/turtle_compliant.xml (default blade compliance, i.e. whatever
cad_exports/compliant_flipper.json in turtle_simulator generated) and writes:

  turtle_compliant_mjpc.xml   the robot, with the changes below
  assets/                     only the meshes that model uses

Changes for MJPC:
  * All 10 actuators become position servos (ctrl = joint target). Gains and force limit are
    turtle_sim.py's --servo placeholders (SERVO_KP, SERVO_KV, SERVO_FORCE_LIMIT), applied to the
    rear hips too. The plain model's actuators are kp=1 springs that turtle_sim.py wraps in an
    outer PD loop, which a planner cannot reproduce from ctrl alone.
  * ctrlrange per joint (no joint limits exist in the CAD export, so these are placeholders).
  * Contacts disabled, as turtle_sim.py does (open water, nothing to touch).
  * Task sites on the shell: base_cog, head (nose) and tail.
  * The XML declaration and generator comments are stripped so the file can be <include>d.

Re-run after regenerating turtle_compliant.xml in turtle_simulator (e.g. after a graft or a
change to the blade's shear modulus). Joint and actuator names are unchanged, so the task code
and reference_gait.xml keep working as long as turtle_simulator keeps its names stable.
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

# Joint-target ranges in rad. The reference gait spans about +-1.05 (joint 2), +-0.35 (joint 1)
# and -0.42..0.42 (joint 3); turtle_sim.py's pitch command moves the rear hips by up to +-60 deg.
CTRLRANGE = {
    "shoulderL1": 1.2, "shoulderL2": 1.6, "shoulderL3": 1.2,
    "shoulderR1": 1.2, "shoulderR2": 1.6, "shoulderR3": 1.2,
    "hip_L1": 1.05, "hip_L2": 1.05, "hip_R1": 1.05, "hip_R2": 1.05,
}
ROOT_BODY = "fr13_s105k"
# Shell frame: -y is forward (head), +z is up. Same points as turtle_3dswimming.
SITES = """      <!-- MJPC task sites (added by prepare_model.py). Shell frame: -y forward, +z up. -->
      <site name="base_cog" pos="-0.196495 0.00135248 0.0717682" size="0.01" group="5"/>
      <site name="head" pos="-0.196 -0.22 0.072" size="0.01" group="5"/>
      <site name="tail" pos="-0.196 0.28 0.072" size="0.01" group="5"/>
"""


def main():
  here = Path(__file__).resolve().parent
  ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  ap.add_argument("--turtle-sim", type=Path, required=True, help="path to the turtle_simulator repo")
  ap.add_argument("--model", default="turtle_compliant", help="model in turtle_simulator/mujoco_models/")
  args = ap.parse_args()

  sim = args.turtle_sim.resolve()
  sys.path.insert(0, str(sim))
  import turtle_sim  # servo constants live there

  src = sim / "mujoco_models" / f"{args.model}.xml"
  xml = src.read_text()

  # Strip the XML declaration and the onshape-to-robot header comments.
  xml = re.sub(r"<\?xml[^?]*\?>\s*", "", xml)
  xml = re.sub(r"<!--[^\n]*(Generated using|cad\.onshape\.com)[^\n]*-->\s*", "", xml)
  header = (f"<!-- Generated by prepare_model.py from turtle_simulator/mujoco_models/{args.model}.xml;"
            " do not edit by hand. -->\n")

  # Contacts off.
  xml, n = re.subn(r'(<option noslip_iterations="1"/>)', r'<option noslip_iterations="1">\n    <flag contact="disable"/>\n  </option>', xml)
  assert n == 1, "option block not found"

  # Task sites right after the root's free joint.
  xml, n = re.subn(r'(<joint name="world_frame_to_base" type="free"[^>]*/>\n)', r"\1" + SITES, xml)
  assert n == 1, "root free joint not found"

  # Servo actuators.
  kp, kv, flim = turtle_sim.SERVO_KP, turtle_sim.SERVO_KV, turtle_sim.SERVO_FORCE_LIMIT
  def servo(m):
    name, joint = m.group(1), m.group(2)
    r = CTRLRANGE[joint]
    return (f'<position name="{name}" joint="{joint}" kp="{kp:g}" kv="{kv:g}" '
            f'forcerange="-{flim:g} {flim:g}" ctrlrange="-{r:g} {r:g}"/>')
  xml, n = re.subn(r'<position class="turtle" name="([^"]+)" joint="([^"]+)"/>', servo, xml)
  assert n == len(CTRLRANGE), f"expected {len(CTRLRANGE)} actuators, replaced {n}"

  out = here / "turtle_compliant_mjpc.xml"
  out.write_text(header + xml)

  # Copy only the meshes the model references.
  assets = here / "assets"
  if assets.exists():
    shutil.rmtree(assets)
  assets.mkdir()
  files = sorted(set(re.findall(r'<mesh[^>]*file="([^"]+)"', xml)))
  for f in files:
    shutil.copy2(sim / "mujoco_models" / "assets" / f, assets / f)
  print(f"wrote {out.name} and {len(files)} meshes to assets/ "
        f"(servo kp={kp:g} kv={kv:g} force limit {flim:g} N m)")


if __name__ == "__main__":
  main()
