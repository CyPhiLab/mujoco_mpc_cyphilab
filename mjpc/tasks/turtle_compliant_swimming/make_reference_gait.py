#!/usr/bin/env python3
"""Write reference_gait.xml: the turtle_simulator straight-swimming gait as servo targets.

The table is what `turtle_sim.py --servo --controls 1 0 0 0` sends to the actuators over one
stroke, sampled uniformly in time, so the MJPC task starts from the same gait as the simulator.

  python make_reference_gait.py --turtle-sim ../../../../turtle_simulator

Front limbs: the Cornelia (van der Geest et al. 2023) joint trajectories from
turtle_ctrl/biological_oracles.py, mapped to the model's joints with FRONT_JOINT_MAP and scaled
by SERVO_STROKE_SCALE, both imported from turtle_sim.py. Rear limbs: held at zero. turtle_sim.py
adds a +-5 deg, 1 Hz hip_L2/R2 wiggle that is not periodic in the stroke and is left out here.

Time convention (as in turtle_sim.py): the oracle is called with t_new = t0 + sw * t and
evaluates it at phase sw * t_new (mod 4.3), so one stroke lasts 4.3 / sw^2 s and the table's
phase 0 is the simulator's pose at t = 0.
"""
import argparse
import sys
from pathlib import Path

import numpy as np

ACTUATORS = ["shoulderL1", "shoulderL2", "shoulderL3", "shoulderR1", "shoulderR2", "shoulderR3",
             "hip_L1", "hip_L2", "hip_R1", "hip_R2"]
N_PASSIVE_TWIST = 16  # shoulderL3_twist1..8, shoulderR3_twist1..8 in turtle_compliant.xml


def main():
  here = Path(__file__).resolve().parent
  ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  ap.add_argument("--turtle-sim", type=Path, required=True, help="path to the turtle_simulator repo")
  ap.add_argument("--samples", type=int, default=128,
                  help="samples per stroke (MuJoCo caps one numeric at 500 values)")
  ap.add_argument("--out", type=Path, default=here / "reference_gait.xml")
  args = ap.parse_args()

  sys.path.insert(0, str(args.turtle_sim.resolve()))
  from turtle_ctrl.turtle_ctrl_factory import cornelia_joint_space_trajectory_tracking_control_factory
  import turtle_sim

  # Same settings as TurtleSimulator.__init__.
  sw = 1.5
  t_new0 = (4.3 / sw) * 0.32
  ctrl_fn = cornelia_joint_space_trajectory_tracking_control_factory(kp=[2.0] * 6, sw=sw)
  period = 4.3 / sw**2

  table = np.zeros((args.samples, len(ACTUATORS)))
  for k in range(args.samples):
    t = period * k / args.samples
    _, aux = ctrl_fn(t=t_new0 + sw * t, q=np.zeros(6))
    q_arm_des = aux["q_des"]  # controller convention, --controls 1 0 0 0 adds nothing
    table[k, :6] = turtle_sim.FRONT_JOINT_MAP.T @ (turtle_sim.SERVO_STROKE_SCALE * q_arm_des)

  # Keyframe: start on the gait (passive blade joints at rest) so the run has no start-up jump.
  q0 = table[0]
  qpos = [0, 0, 0, 1, 0, 0, 0]
  qpos += list(q0[0:3]) + [0.0] * (N_PASSIVE_TWIST // 2)  # left front + left blade
  qpos += list(q0[3:6]) + [0.0] * (N_PASSIVE_TWIST // 2)  # right front + right blade
  qpos += list(q0[6:10])

  def fmt(v):
    return " ".join(f"{x:.6g}" for x in v)

  rows = "\n".join(f'    <numeric name="turtle_gait_{n}" data="{fmt(table[:, j])}"/>'
                   for j, n in enumerate(ACTUATORS))
  rng = np.stack([table.min(0), table.max(0)], 1)
  ranges = "\n".join(f"       {n:<11s} [{lo:+.3f}, {hi:+.3f}] rad" for n, (lo, hi) in zip(ACTUATORS, rng))
  xml = f"""<!-- Generated by make_reference_gait.py from turtle_simulator; do not edit by hand.
     Reference gait: servo targets of turtle_sim.py (servo mode, controls 1 0 0 0) over one stroke.
     One numeric per actuator (turtle_gait_<actuator name>), {args.samples} samples uniform in time,
     period {period:.6f} s; sample 0 is the simulator's pose at t = 0.
     Ranges:
{ranges}
-->
<mujoco>
  <custom>
    <numeric name="turtle_gait_period" data="{period:.6f}"/>
{rows}
  </custom>
  <keyframe>
    <key name="home" qpos="{fmt(qpos)}" ctrl="{fmt(q0)}"/>
  </keyframe>
</mujoco>
"""
  args.out.write_text(xml)
  print(f"wrote {args.out}: {args.samples} samples, period {period:.4f} s")
  print(ranges)


if __name__ == "__main__":
  main()
